"""Regenerate `tables/` from `metrics/`. Nothing here is typed by hand.

Contract §0.10: a number not bound to a receipt does not exist, and no figure or
table is written by hand. Every cell below is read out of `metrics/*.json`, so a
table that disagrees with the metrics is a bug in this script rather than a
number someone edited.

    .venv/Scripts/python.exe research/experiments/EXP-0101/scripts/make_tables.py
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

EXPERIMENT = Path(__file__).resolve().parents[1]

ARM_ORDER = (
    "current",
    "baseline",
    "challenger",
    "challenger_no_spatial",
    "challenger_no_type_reasoning",
    "challenger_no_content",
)

HEADLINE = (
    ("alignment_precision", "Alignment precision"),
    ("alignment_recall", "Alignment recall"),
    ("semantic_change_precision", "Semantic-change precision"),
    ("semantic_change_recall", "Semantic-change recall"),
    ("layout_only_false_positive_rate", "Layout-only false positive"),
    ("layout_only_unresolved_rate", "Layout-only unresolved"),
    ("layout_only_false_invalidation_rate", "Layout-only false invalidation"),
    ("critical_change_recall", "Critical change recall"),
    ("critical_change_surfaced_rate", "Critical change surfaced"),
    ("critical_change_labelled_rate", "Critical change labelled"),
    ("critical_numeric_change_recall", "Critical numeric recall"),
    ("identity_false_merges", "Identity false merge"),
    ("identity_false_splits", "Identity false split"),
    ("critical_false_merges", "Critical false merge"),
    ("downstream_impact_recall", "Downstream impact recall"),
    ("selective_full_equivalence", "Selective/full equivalence"),
)


def _load(name: str) -> Any:
    return json.loads((EXPERIMENT / "metrics" / name).read_text(encoding="utf-8"))


def _cell(record: Any) -> str:
    if record is None:
        return "n/a"
    if isinstance(record, dict):
        value = record.get("value")
        if value is None:
            return "n/a"
        return f"{value:.4f} ({record['numerator']}/{record['denominator']})"
    if isinstance(record, (int, float)):
        return f"{record:.4f}"
    return str(record)


#: Stamped on every table. A table is the artifact most likely to travel on its
#: own into a deck or a draft, so the restriction travels with it rather than
#: living only in a receipt nobody opened.
_DISCLOSURE = (
    "> **NOT CLEARED FOR EXTERNAL DISCLOSURE.** Gate 6 is BLOCKED and the "
    "prior-art\n> baseline was implemented without §15.3 role separation. "
    "Internal and\n> exploratory use only — see "
    "`receipts/clean-room-provenance.json`.\n"
)


def _write(name: str, body: str) -> None:
    path = EXPERIMENT / "tables" / name
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = body.split("\n")
    # After the H1, before anything a reader would quote.
    body = "\n".join([lines[0], "", _DISCLOSURE, *lines[1:]])
    # LF explicitly -- see the note in run_experiment._write_json.
    path.write_text(body, encoding="utf-8", newline="\n")


def headline(summary: dict[str, Any]) -> None:
    lines = [
        "# EXP-0101 headline metrics",
        "",
        "*Generated by `scripts/make_tables.py` from `metrics/summary.json`.*",
        "",
        "Every cell is `rate (numerator/denominator)`. `n/a` means the population",
        "was empty, which is not the same as a rate of zero.",
        "",
        "| metric | " + " | ".join(ARM_ORDER) + " |",
        "|---|" + "---|" * len(ARM_ORDER),
    ]
    for key, label in HEADLINE:
        cells = [_cell(summary[arm][key]) for arm in ARM_ORDER]
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    lines.append(
        "| Alignment F1 | "
        + " | ".join(f"{summary[arm]['alignment_f1']:.4f}" for arm in ARM_ORDER)
        + " |"
    )
    lines.append(
        "| Mean rebuild fraction | "
        + " | ".join(f"{summary[arm]['mean_rebuild_fraction']:.4f}" for arm in ARM_ORDER)
        + " |"
    )
    lines.append("")
    lines.append("## 95% bootstrap confidence intervals")
    lines.append("")
    lines.append("*10,000 resamples, fixed seed, paired at document-pair level.*")
    lines.append("")
    interval_keys = sorted(summary[ARM_ORDER[0]]["confidence_intervals"])
    lines.append("| metric | " + " | ".join(ARM_ORDER) + " |")
    lines.append("|---|" + "---|" * len(ARM_ORDER))
    for key in interval_keys:
        cells = []
        for arm in ARM_ORDER:
            interval = summary[arm]["confidence_intervals"][key]
            cells.append(
                "n/a" if interval is None else f"[{interval[0]:.4f}, {interval[1]:.4f}]"
            )
        lines.append(f"| {key} | " + " | ".join(cells) + " |")
    _write("headline-metrics.md", "\n".join(lines) + "\n")


def per_class(per_mutation: dict[str, Any]) -> None:
    metrics = (
        "semantic_change_recall",
        "layout_only_false_invalidation_rate",
        "critical_change_recall",
        "downstream_impact_recall",
        "selective_full_equivalence",
    )
    classes = sorted(per_mutation[ARM_ORDER[0]])
    lines = [
        "# EXP-0101 per-mutation-class breakdown",
        "",
        "*Generated by `scripts/make_tables.py` from `metrics/per-mutation-class.json`.*",
        "",
    ]
    for metric in metrics:
        lines.append(f"## {metric}")
        lines.append("")
        lines.append("| mutation class | " + " | ".join(ARM_ORDER) + " |")
        lines.append("|---|" + "---|" * len(ARM_ORDER))
        for mutation in classes:
            cells = [_cell(per_mutation[arm][mutation][metric]) for arm in ARM_ORDER]
            lines.append(f"| {mutation} | " + " | ".join(cells) + " |")
        lines.append("")
    _write("per-mutation-class.md", "\n".join(lines) + "\n")


def statistics(stats: dict[str, Any]) -> None:
    lines = [
        "# EXP-0101 significance tests",
        "",
        f"*{stats['test']}. {stats['multiple_comparison']}.*",
        f"*Reference arm: `{stats['reference_arm']}`.*",
        "",
        "`arm better` counts cases the arm got right and the reference got wrong;",
        "`reference better` the reverse. Concordant cases carry no information",
        "about a difference and are not in the denominator.",
        "",
        "| comparison | arm better | reference better | discordant | p (exact) | p (Holm) |",
        "|---|---|---|---|---|---|",
    ]
    for label in sorted(stats["tests"]):
        test = stats["tests"][label]
        lines.append(
            f"| `{label}` | {test['arm_better']} | {test['current_better']} | "
            f"{test['discordant']} | {test['p_exact']:.3e} | "
            f"{test['p_holm_bonferroni']:.3e} |"
        )
    _write("statistics.md", "\n".join(lines) + "\n")


def gates(summary: dict[str, Any], stats: dict[str, Any]) -> None:
    """The six promotion gates plus Contract A's three, scored mechanically.

    Two of the nine are not a number and are marked as what they are: an
    evidence check, not a measurement. Writing them as PASS on the strength of a
    file existing would be the sort of green tick this repository exists to
    distrust, so the cell says which record was checked.
    """
    current = summary["current"]
    lines = [
        "# EXP-0101 promotion gate adjudication",
        "",
        "*Generated by `scripts/make_tables.py`. The rule for each gate is in the",
        "row, so a reader can disagree with the rule rather than the arithmetic.*",
        "",
        "| gate | rule | challenger | verdict |",
        "|---|---|---|---|",
    ]

    def verdict(passed: bool) -> str:
        return "**PASS**" if passed else "**FAIL**"

    challenger = summary["challenger"]

    quality = (
        challenger["semantic_change_recall"]["value"]
        >= current["semantic_change_recall"]["value"]
    )
    lines.append(
        "| 1 quality non-regression | semantic-change recall >= CURRENT | "
        f"{challenger['semantic_change_recall']['value']:.4f} vs "
        f"{current['semantic_change_recall']['value']:.4f} | {verdict(quality)} |"
    )

    catastrophic = (
        challenger["critical_false_merges"]["value"] == 0.0
        and challenger["selective_full_equivalence"]["value"] == 1.0
    )
    lines.append(
        "| 2 catastrophic failure non-regression | zero critical false merges and "
        "selective/full equivalence 1.0 | "
        f"false merges {challenger['critical_false_merges']['value']:.4f}, "
        f"equivalence {challenger['selective_full_equivalence']['value']:.4f} | "
        f"{verdict(catastrophic)} |"
    )

    budget = challenger["mean_rebuild_fraction"] <= current["mean_rebuild_fraction"]
    lines.append(
        "| 3 latency/cost budget | mean rebuild fraction <= CURRENT (no API spend "
        "in this experiment) | "
        f"{challenger['mean_rebuild_fraction']:.4f} vs "
        f"{current['mean_rebuild_fraction']:.4f} | {verdict(budget)} |"
    )

    lines.append(
        "| 4 reproducibility | `scripts/verify_receipts.py` reruns the frozen "
        "manifest and compares every metric byte for byte | evidence check, see "
        "`receipts/reproducibility.json` | see that file |"
    )

    lines.append(
        "| 5 permission/security invariants | not engaged: this experiment reads "
        "no tenant data, opens no connection and touches no permission path | "
        "no cross-tenant surface | **N/A** |"
    )

    lines.append(
        "| 6 license/FTO | clean-room evidence recorded for the YELLOW baseline; "
        "design-around review for external language NOT done | "
        "`receipts/clean-room-provenance.json` | **BLOCKED on review** |"
    )

    critical_ok = (
        challenger["critical_change_recall"]["value"]
        >= current["critical_change_recall"]["value"]
    )
    lines.append(
        "| A-i critical semantic recall | >= CURRENT on the high-risk set, target "
        "1.0 | "
        f"{challenger['critical_change_recall']['value']:.4f} vs "
        f"{current['critical_change_recall']['value']:.4f} | "
        f"{verdict(critical_ok)} |"
    )
    lines.append(
        "| A-ii zero critical false merges | critical false merge rate 0 | "
        f"{challenger['critical_false_merges']['value']:.4f} | "
        f"{verdict(challenger['critical_false_merges']['value'] == 0.0)} |"
    )
    ambiguous_reviewable = challenger["identity_false_splits"]["value"] == 0.0
    lines.append(
        "| A-iii ambiguous stays reviewable | no gold pair silently split; "
        "abstentions carry candidates | "
        f"false split rate {challenger['identity_false_splits']['value']:.4f} | "
        f"{verdict(ambiguous_reviewable)} |"
    )

    lines.append("")
    lines.append("## Where the significance sits")
    lines.append("")
    for label in sorted(stats["tests"]):
        if not label.startswith(("challenger::", "challenger_no_content::")):
            continue
        test = stats["tests"][label]
        lines.append(
            f"- `{label}`: {test['arm_better']} vs {test['current_better']} "
            f"discordant, Holm-adjusted p = {test['p_holm_bonferroni']:.3e}"
        )

    lines.append("")
    lines.append("## What a mechanical verdict cannot see")
    lines.append("")
    if challenger["mean_rebuild_fraction"] == 1.0 and current["mean_rebuild_fraction"] == 1.0:
        lines.append(
            "- **Gate 2's `PASS` is not evidence about the challenger.** Both arms "
            "rebuild every artifact in every case "
            f"(mean rebuild fraction {challenger['mean_rebuild_fraction']:.4f}), "
            "because an evidence id is derived from the document version, so every "
            "matched unit reports `EVIDENCE_MOVED` and lands in "
            "`changed_logical_ids`. Equivalence holds because nothing is ever "
            "carried over, not because the diff was right. The baseline, which "
            "does not have that behaviour, scores "
            f"{summary['baseline']['selective_full_equivalence']['value']:.4f}."
        )
        lines.append(
            "- **Gate 3's `PASS` is a tie at the worst possible value**, for the "
            "same reason. Selective recompilation currently reduces to a full "
            "rebuild on this fixture for every arm that goes through "
            "`akc_cir.semantic_diff`."
        )
    fp_value = challenger["layout_only_false_positive_rate"]["value"]
    inval_value = challenger["layout_only_false_invalidation_rate"]["value"]
    current_inval = current["layout_only_false_invalidation_rate"]["value"]
    lines.append(
        f"- **The layout-only gain is smaller than the false-positive row says.** "
        f"The challenger's false-positive rate is {fp_value:.4f} against CURRENT's "
        f"{current['layout_only_false_positive_rate']['value']:.4f}, but counting "
        f"abstentions the false-invalidation rate is {inval_value:.4f} against "
        f"{current_inval:.4f}. Most of the gain is false positives converted into "
        "unresolved identities, and both end in a rebuild."
    )
    _write("gate-adjudication.md", "\n".join(lines) + "\n")


def main() -> int:
    summary = _load("summary.json")
    headline(summary)
    per_class(_load("per-mutation-class.json"))
    stats = _load("statistics.json")
    statistics(stats)
    gates(summary, stats)
    print("tables written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
